#!/usr/bin/env python3
"""Generate Rust/UI electrical catalogs from the shared registry; --check verifies them."""
import argparse,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
rows=[]
for line in (ROOT/'config/electrical-measurements.def').read_text().splitlines():
 m=re.fullmatch(r'ELECTRICAL\((\d+), (\d+), (\d+), (\w+), "([^"]+)", (\d+), (\d+)\)',line)
 if m:
  c,a,s,k,u,d,h=m.groups();rows.append(dict(cluster=int(c),attribute=int(a),subfield=int(s),key=k,unit=u,divisor=int(d),metric=int(h),label=k.replace('_',' ').capitalize()))
assert len(rows)==25 and len({r['key'] for r in rows})==25
assert {r['metric'] for r in rows}=={4,*range(21,45)}
outputs={
 'microhad/webui/src/electrical.ts':'// Generated by scripts/generate-electrical-bindings.py.\nexport const electricalDefinitions = '+json.dumps(rows,indent=2)+' as const\n',
 'io.github.microhad/app/src/main/java/io/github/microhad/ElectricalMeasurements.kt':'// Generated by scripts/generate-electrical-bindings.py.\npackage io.github.microhad\ninternal val electricalMetricNames = mapOf(\n'+',\n'.join(f'    {r["metric"]} to "{r["label"]}"' for r in rows)+'\n)\n',
 'micro-thread-matter-daemon/src/electrical_definitions.rs':'// Generated by scripts/generate-electrical-bindings.py.\npub const DEFINITIONS: &[Definition] = &[\n'+''.join('    Definition{cluster:%s,attribute:%s,sub:%s,key:"%s",unit:"%s",divisor:%s.0},\n'%(r['cluster'],r['attribute'],r['subfield'],r['key'],r['unit'],r['divisor']) for r in rows)+'];\n',
}
parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
for name,text in outputs.items():
 path=ROOT/name
 if args.check:
  if not path.exists() or path.read_text()!=text:raise SystemExit('Stale generated electrical catalog: '+name)
 else:path.write_text(text)
print('Electrical catalogs verified' if args.check else 'Electrical catalogs generated')
