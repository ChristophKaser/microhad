#!/usr/bin/env python3
"""Generate owned C++03 protobuf messages and direct nanopb codecs for Matter IPC."""
import json
from pathlib import Path
import re


def write(path,text):
    if not path.exists() or path.read_text()!=text:path.write_text(text)


def generate(out):
    root=Path(__file__).resolve().parents[1]
    schema=json.loads((out/'schema.json').read_text())
    names=re.findall(r'^message (\w+)',(root/'protocol/matter-ipc-v3.proto').read_text(),re.M)
    schema={name:schema[name] for name in names}
    ordered=[]
    def visit(name):
        if name in ordered:return
        for f in schema[name]:
            if f['type']==11:visit(f['message'])
        ordered.append(name)
    for name in names:visit(name)
    types={1:'double',4:'uint64_t',8:'bool',9:'std::string',12:'std::vector<unsigned char>',13:'uint32_t',18:'int64_t'}
    def field(f):return f['name']+'_value' if f['name'] in ('null','unsigned') else f['name']
    def typ(f):return types.get(f['type'],f['message'])
    h='''// Generated by scripts/generate-matter-bindings.py; do not edit.
#ifndef MICROHAD_MATTER_MESSAGES_PB_H
#define MICROHAD_MATTER_MESSAGES_PB_H
#include <stdint.h>
#include <string>
#include <vector>
namespace MatterProto {
template<class T> struct Optional {
    bool present; T value;
    Optional():present(false),value(){}
    Optional(const T& v):present(true),value(v){}
    Optional& operator=(const T& v){value=v;present=true;return *this;}
    bool operator==(const Optional& other) const{return present==other.present&&(!present||value==other.value);}
};
'''
    for name in ordered:
        h+='struct '+name+' {\n'
        for f in schema[name]:h+='    '+('std::vector<'+typ(f)+'>' if f['repeated'] else 'Optional<'+typ(f)+'>')+' '+field(f)+';\n'
        h+='    bool operator==(const '+name+'& other) const {return '+('&&'.join(field(f)+'==other.'+field(f) for f in schema[name]) if schema[name] else '(void)other,true')+';}\n};\n'
    h+='}\n#endif\n';write(out/'matter_messages.pb.h',h.replace('>>','> >'))
    c='// Generated direct typed nanopb codecs; no JSON or string-keyed fields.\nnamespace MatterProto {\n'
    for name in ordered:
        c+='bool write(pb_ostream_t*,const '+name+'&,unsigned);\nbool read(pb_istream_t*,'+name+'*,unsigned,unsigned*);\n'
    c+='''template<class T> bool writeNested(pb_ostream_t* s,const T& v,unsigned depth){
    pb_ostream_t size=PB_OSTREAM_SIZING;
    if(!write(&size,v,depth+1)||!pb_encode_varint(s,size.bytes_written))return false;
    return s->callback?write(s,v,depth+1):pb_write(s,0,size.bytes_written);
}
template<class T> bool readNested(pb_istream_t* s,T* v,unsigned depth,unsigned* unknown){
    pb_istream_t child;if(!pb_make_string_substream(s,&child))return false;
    if(!read(&child,v,depth+1,unknown))return false;
    return pb_close_string_substream(s,&child);
}
'''
    for name in ordered:
        fs=schema[name]
        c+='bool write(pb_ostream_t* s,const '+name+'& v,unsigned depth){\n    if(depth>16)return false;\n    (void)s;(void)v;\n'
        if fs and fs[0]['oneof']:
            c+='    if('+ '+'.join('(v.'+field(f)+'.present?1:0)' for f in fs)+'>1)return false;\n'
        for f in fs:
            fn=field(f);t=f['type'];wt='PB_WT_64BIT' if t==1 else 'PB_WT_STRING' if t in (9,11,12) else 'PB_WT_VARINT'
            if f['repeated']:c+='    if(v.'+fn+'.size()>512)return false;\n    for(size_t i=0;i<v.'+fn+'.size();++i){\n';x='v.'+fn+'[i]'
            else:c+='    if(v.'+fn+'.present){\n';x='v.'+fn+'.value'
            c+=f'        if(!pb_encode_tag(s,{wt},{f["tag"]}))return false;\n'
            if t in (4,8,13):expr=f'pb_encode_varint(s,{x})'
            elif t==18:expr=f'pb_encode_svarint(s,{x})'
            elif t==1:expr=f'(std::isfinite({x})&&pb_encode_fixed64(s,&{x}))'
            elif t in (9,12):
                expr=f'({x}.size()<=2048'+(f'&&validUtf8({x})' if t==9 else '')+f'&&pb_encode_string(s,reinterpret_cast<const pb_byte_t*>({x}.empty()?0:&{x}[0]),{x}.size()))'
            else:expr=f'writeNested(s,{x},depth)'
            c+='        if(!'+expr+')return false;\n    }\n'
        c+='    return true;\n}\n'
        c+='bool read(pb_istream_t* s,'+name+'* out,unsigned depth,unsigned* unknown){\n    if(depth>16)return false;\n    '+name+' v;\n    while(s->bytes_left){\n        pb_wire_type_t wt;uint32_t tag;bool eof=false;if(!pb_decode_tag(s,&wt,&tag,&eof)||tag==0)return false;\n        switch(tag){\n'
        for f in fs:
            fn=field(f);t=f['type'];wt='PB_WT_64BIT' if t==1 else 'PB_WT_STRING' if t in (9,11,12) else 'PB_WT_VARINT'
            c+=f'        case {f["tag"]}:{{\n'
            if f['repeated'] and t in (4,8,13,18):
                c+=f'            if(wt==PB_WT_STRING){{pb_istream_t packed;if(!pb_make_string_substream(s,&packed))return false;while(packed.bytes_left){{if(v.{fn}.size()>=512)return false;uint64_t n;if(!pb_decode_varint(&packed,&n)'+('||n>0xffffffffUL' if t==13 else '||n>1' if t==8 else '')+f')return false;v.{fn}.push_back(static_cast<{typ(f)}>(n));}}if(!pb_close_string_substream(s,&packed))return false;break;}}\n'
            c+=f'            if(wt!={wt})return false;\n'
            if f['repeated']:c+=f'            if(v.{fn}.size()>=512)return false;v.{fn}.push_back({typ(f)}());\n';x='v.'+fn+'.back()'
            else:
                if f['oneof']:c+='            if('+ '||'.join('v.'+field(q)+'.present' for q in fs)+')return false;\n'
                else:c+=f'            if(v.{fn}.present)return false;\n'
                c+=f'            v.{fn}.present=true;\n';x='v.'+fn+'.value'
            if t in (4,8,13):c+='            uint64_t n;if(!pb_decode_varint(s,&n)'+('||n>0xffffffffUL' if t==13 else '||n>1' if t==8 else '')+f')return false;{x}=static_cast<{typ(f)}>(n);\n'
            elif t==18:c+=f'            if(!pb_decode_svarint(s,&{x}))return false;\n'
            elif t==1:c+=f'            if(!pb_decode_fixed64(s,&{x})||!std::isfinite({x}))return false;\n'
            elif t in (9,12):c+='            uint32_t n;if(!pb_decode_varint32(s,&n)||n>2048||n>s->bytes_left)return false;'+x+'.resize(n);if(n&&!pb_read(s,reinterpret_cast<pb_byte_t*>(&'+x+'[0]),n))return false;'+(f'if(!validUtf8({x}))return false;' if t==9 else '')+'\n'
            else:c+=f'            if(!readNested(s,&{x},depth,unknown))return false;\n'
            c+='            break;}\n'
        c+='        default:if(!pb_skip_field(s,wt))return false;++*unknown;break;\n        }\n    }\n    *out=v;return true;\n}\n'
    c+='}\n';write(out/'matter_codec.inc',c.replace('return false;','{ return false; }'))
    # Generic values exist only in the public JSON boundary adapter, never in IPC.
    j='// Generated typed/public-JSON boundary conversion helpers.\nnamespace MatterProto {\n'
    for name in ordered:
        j+='bool fromValue(const Proto::Value&,'+name+'*);\nProto::Value toValue(const '+name+'&);\n'
    def valput(f,x):
        t=f['type']
        return {1:f'jsonFloat({x})',4:f'jsonUInt({x})',8:f'jsonBool({x})',9:f'jsonText({x})',12:f'jsonBytes({x})',13:f'jsonUInt({x})',18:f'jsonInt({x})'}.get(t,f'toValue({x})')
    def valget(f,x,y):
        t=f['type']
        return {1:f'getFloat({x},&{y})',4:f'getUInt({x},&{y})',8:f'getBool({x},&{y})',9:f'getText({x},&{y})',12:f'getBytes({x},&{y})',13:f'getUInt32({x},&{y})',18:f'getInt({x},&{y})'}.get(t,f'fromValue({x},&{y})')
    for name in ordered:
        j+='bool fromValue(const Proto::Value& v,'+name+'* out){\n    if(v.type!=Proto::Value::Map)return false;\n    '+name+' result;\n'
        for f in schema[name]:
            fn=field(f);j+='    if(const Proto::Value* p=Proto::field(v,"'+f['name']+'")){\n'
            nullable_scalar=(name=='BindingTarget' and f['name']=='node') or (name=='ButtonEvent' and f['name'] in ('position','press_count'))
            if nullable_scalar:j+='        if(p->type!=Proto::Value::Null){\n'
            if f['repeated']:
                j+='        if(p->type!=Proto::Value::Array)return false;\n        result.'+fn+'.resize(p->items.size());\n        for(size_t i=0;i<p->items.size();++i)if(!'+valget(f,'p->items[i]','result.'+fn+'[i]')+')return false;\n'
            else:j+='        result.'+fn+'.present=true;if(!'+valget(f,'*p','result.'+fn+'.value')+')return false;\n'
            if nullable_scalar:j+='        }\n'
            j+='    }\n'
        j+='    *out=result;return true;\n}\nProto::Value toValue(const '+name+'& v){\n    Proto::Value out;out.type=Proto::Value::Map;(void)v;\n'
        for f in schema[name]:
            fn=field(f)
            if f['repeated']:j+='    if(!v.'+fn+'.empty()){Proto::Value a;a.type=Proto::Value::Array;for(size_t i=0;i<v.'+fn+'.size();++i)a.items.push_back('+valput(f,'v.'+fn+'[i]')+');Proto::add(&out,"'+f['name']+'",a);}\n'
            else:j+='    if(v.'+fn+'.present)Proto::add(&out,"'+f['name']+'",'+valput(f,'v.'+fn+'.value')+');\n'
        j+='    return out;\n}\n'
    j+='}\n';write(out/'matter_json.inc',j)
    rs=(out/'protobuf.rs').read_text();typed=rs[:rs.index('fn to_')].replace('use prost::Message;\nuse super::{Value, ProtocolError};\n','')
    # Strict wire validation uses integer schema IDs, fixed counters and tags;
    # it never looks up field/message names or allocates hash tables.
    maximum=max(len(fields) for fields in schema.values())
    if maximum>64:raise SystemExit('Matter strict validator supports up to 64 fields per message')
    typed+=f'pub(super) const MAX_FIELDS: usize = {maximum};\n'
    typed+=f'pub(super) const IPC_ENVELOPE_SCHEMA: usize = {names.index("IpcEnvelope")};\n'
    typed+="pub(super) struct Field {pub tag:u32,pub kind:u32,pub message:usize,pub repeated:bool,pub oneof:bool}\n"
    typed+="pub(super) fn schema(id:usize)->&'static [Field]{SCHEMAS[id]}\nconst SCHEMAS:&[&[Field]]=&[\n"
    for name in names:
        typed+='&[\n'
        for f in schema[name]:
            child=names.index(f['message']) if f['type']==11 else 0
            typed+=f'Field{{tag:{f["tag"]},kind:{f["type"]},message:{child},repeated:{str(f["repeated"]).lower()},oneof:{str(f["oneof"]).lower()}}},\n'
        typed+='],\n'
    typed+='];\npub(super) trait Bounded {fn bounded(&self,depth:usize)->bool;}\n'
    def check(f,x):
        return f'{x}.bounded(depth+1)' if f['type']==11 else f'{x}.is_finite()' if f['type']==1 else 'true'
    def variant(name):return ''.join(part.title() for part in name.split('_'))
    for name in names:
        fs=schema[name];typed+=f'impl Bounded for {name} {{fn bounded(&self,depth:usize)->bool{{if depth>16{{return false;}}\n'
        if fs and fs[0]['oneof']:
            typed+='match self.choice.as_ref(){\n'
            for f in fs:typed+=f'Some({name}Choice::{variant(f["name"])}(value))=>{{let _=value;{check(f,"value")}}},\n'
            typed+='None=>true,\n}\n'
        else:
            for f in fs:
                field='r#type' if f['name']=='type' else f['name']
                if f['repeated']:
                    typed+=f'if self.{field}.len()>512{{return false;}}\n'
                    if f['type'] in (1,11):typed+=f'for value in &self.{field}{{if !{check(f,"value")}{{return false;}}}}\n'
                elif f['type'] in (1,11):typed+=f'if let Some(value)=&self.{field}{{if !{check(f,"value")}{{return false;}}}}\n'
            typed+='true\n'
        typed+='}}\n'
    write(out/'matter_typed.rs',typed)

if __name__=='__main__':generate(Path(__file__).resolve().parents[1]/'protocol/generated')
