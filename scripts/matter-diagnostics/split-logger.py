#!/usr/bin/env python3
"""Split the pinned generated logger, retaining all functions and attribute cases."""
import argparse
from pathlib import Path
import re


def split(source: Path) -> dict:
    relative = 'zzz_generated/chip-tool/zap-generated/cluster/logging'
    original = (source / relative / 'DataModelLogger.cpp').read_text()
    starts = list(re.finditer(r'^CHIP_ERROR\b', original, re.MULTILINE))
    if len(starts) != 531:
        raise ValueError('Unexpected pinned DataModelLogger function count')
    prefix = original[:starts[0].start()]
    functions = [original[m.start():starts[i + 1].start() if i + 1 < len(starts) else len(original)]
                 for i, m in enumerate(starts)]
    attributes = [f for f in functions if 'DataModelLogger::LogAttribute(' in f]
    if len(attributes) != 1:
        raise ValueError('Expected one attribute dispatcher')
    attributes = attributes[0]
    cases = list(re.finditer(r'^    case ([A-Za-z_0-9]+)::Id: \{\n', attributes, re.MULTILINE))
    default = attributes.index('    default:\n', cases[-1].start())
    declarations, helpers, dispatch = [], [], []
    for i, match in enumerate(cases):
        end = cases[i + 1].start() if i + 1 < len(cases) else default
        segment = attributes[match.end():end]
        body, replacements = re.subn(r'        break;\n    }\n\s*$', '', segment)
        if replacements != 1 or not body.lstrip().startswith('switch (path.mAttributeId)'):
            raise ValueError('Unexpected cluster case shape: ' + match[1])
        name = 'LogAttributeCluster' + match[1]
        signature = f'CHIP_ERROR DataModelLogger::{name}(const chip::app::ConcreteDataAttributePath & path, chip::TLV::TLVReader * data)'
        declarations.append('static ' + signature.replace('DataModelLogger::', '') + ';\n')
        helpers.append(signature + '\n{\n' + body +
                       '    ChipLogProgress(chipTool, "  Don\'t know how to log attribute value");\n'
                       '    return CHIP_NO_ERROR;\n}\n\n')
        dispatch.append(f'    case {match[1]}::Id: return {name}(path, data);\n')
    switch = attributes.index('    switch (path.mClusterId)')
    replacement = attributes[:switch] + '    switch (path.mClusterId)\n    {\n' + ''.join(dispatch) + attributes[default:]
    # Each original function remains byte-for-byte identical except LogAttribute,
    # whose original cluster bodies are moved verbatim into member functions.
    pieces = [replacement if f is attributes else f for f in functions]
    pieces += helpers
    batches, batch, lines = [], [], 0
    for piece in pieces:
        count = piece.count('\n')
        if batch and count + lines > 1800:
            batches.append(''.join(batch))
            batch, lines = [], 0
        batch.append(piece)
        lines += count
    if batch:
        batches.append(''.join(batch))
    destination = source / relative / 'split'
    destination.mkdir(exist_ok=True)
    names = []
    def write_if_changed(path, text):
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
    for index, batch in enumerate(batches):
        name = f'Logger{index:03d}.cpp'
        names.append(f'  "${{chip_root}}/{relative}/split/{name}",\n')
        write_if_changed(destination / name, prefix + batch)
    write_if_changed(destination / 'sources.gni', 'import("//build_overrides/chip.gni")\n'
                     'diagnostic_logger_sources = [\n' + ''.join(names) + ']\n')
    write_if_changed(source / 'examples/chip-tool/commands/clusters/DiagnosticLoggerDeclarations.h',
                     '// Generated by scripts/matter-diagnostics/split-logger.py\n' + ''.join(declarations))
    return {'original_lines': original.count('\n'), 'original_functions': len(functions),
            'attribute_clusters': len(cases), 'translation_units': len(batches),
            'largest_unit_lines': max((prefix + b).count('\n') for b in batches)}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    args = parser.parse_args()
    print(split(args.source))
