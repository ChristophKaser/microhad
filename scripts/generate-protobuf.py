#!/usr/bin/env python3
"""Regenerate pinned protobuf bindings and bounded native metadata.
Run with tools from protocol/protobuf-requirements.txt installed.
"""
import argparse
import json
import re
import subprocess
import sys
import tempfile
import os
from pathlib import Path
from google.protobuf import descriptor_pb2 as dp
ROOT = Path(__file__).resolve().parents[1]
SOURCES = ['matter-ipc-v3.proto', 'device-cache.proto']

def generate(out):
    subprocess.run([sys.executable, '-m', 'grpc_tools.protoc', '-I'+str(ROOT/'protocol'), '--descriptor_set_out='+str(out/'microhad.pb'), '--python_out='+str(out), *[str(ROOT/'protocol'/s) for s in SOURCES]], check=True)
    plugin=ROOT/'third-party/nanopb/generator/protoc-gen-nanopb'
    subprocess.run([sys.executable, '-m', 'grpc_tools.protoc', '-I'+str(ROOT/'protocol'), '--plugin=protoc-gen-nanopb='+str(plugin), '--nanopb_out='+str(out), str(ROOT/'protocol/device-cache.proto')],check=True,env=dict(os.environ,PATH=str(Path(sys.executable).parent)+os.pathsep+os.environ.get('PATH','')))
    fs=dp.FileDescriptorSet.FromString((out/'microhad.pb').read_bytes())
    msgs={m.name:m for f in fs.file for m in f.message_type}
    cache_fields=set(re.findall(r'CACHE_(?:TEXT|BOOL|INT|NUMBER)\("([^"]+)"', (ROOT/'microhad/include/device_cache_fields.inc').read_text()))
    declared={f.name for f in msgs['CachedDevice'].field}
    if not cache_fields <= declared:raise SystemExit('CachedDevice schema is missing native fields: '+str(sorted(cache_fields-declared)))
    shapes=json.loads((ROOT/'protocol/matter-wire-shapes.json').read_text())
    operations={f.number:f for f in msgs['MessageBody'].field if 1<=f.number<=11}
    for opcode in (9,10,11):
        prefix=operations[opcode].name
        expected=set().union(*(set(fields) for shape,fields in shapes.items() if shape==prefix or shape.startswith(prefix+':')))
        declared={f.name for f in msgs[operations[opcode].type_name.rsplit('.',1)[-1]].field}
        if not expected<=declared:raise SystemExit(f'{prefix} schema is missing action fields: '+str(sorted(expected-declared)))
    data={}
    for name,m in msgs.items():
        if any(f.type not in (1,4,8,9,11,12,13,18) for f in m.field):raise SystemExit("Unsupported protobuf scalar in "+name)
        data[name]=[dict(name=f.name, tag=f.number, type=f.type, message=f.type_name.rsplit('.',1)[-1] if f.type==11 else '', repeated=f.label==3, oneof=f.HasField('oneof_index')) for f in m.field]
    (out/'schema.json').write_text(json.dumps(data,indent=2)+'\n')
    cpp='// Generated by scripts/generate-protobuf.py.\nconst ProtoField protoFields[] = {\n'
    for name,fields in data.items():
        for f in fields:
            cpp+='  {'+', '.join([json.dumps(name),json.dumps(f['name']),str(f['tag']),str(f['type']),json.dumps(f['message']),str(f['repeated']).lower(),str(f['oneof']).lower()])+'},\n'
    cpp+='};\n'
    entries=[(message,f) for message,fields in data.items() for f in fields]
    for suffix,key in [('Name',lambda i:(entries[i][0],entries[i][1]['name'])),('Tag',lambda i:(entries[i][0],entries[i][1]['tag']))]:
        cpp+='const unsigned protoBy'+suffix+'[] = {'+','.join(map(str,sorted(range(len(entries)),key=key)))+'};\n'
    request_names=['']+[operations[i].name for i in range(1,12)]
    ack_names=['']*12
    for i in (6,7,8):
        ack_names[i]=request_names[i].removesuffix('_request')+'_result'
        assert ack_names[i] in {f.name for f in msgs['OperationResult'].field}
    (out/'protobuf_operations.inc').write_text('// Generated by scripts/generate-protobuf.py.\nconst char* const protoRequestNames[] = '+json.dumps(request_names).replace('[','{').replace(']','}')+';\nconst char* const protoAckNames[] = '+json.dumps(ack_names).replace('[','{').replace(']','}')+';\n')
    mapping='// Generated typed Device-to-protobuf field assignments.\n'
    for line in (ROOT/'microhad/include/device_cache_fields.inc').read_text().splitlines():
        match=re.match(r'CACHE_(TEXT|BOOL|INT|NUMBER)\("([^"]+)",\s*(.+)\)',line)
        if not match:continue
        kind,name,args=match.groups()
        member=args.split(',')[0].strip()
        if kind=='TEXT':mapping+=f'bindCallback(&v.{name},typedText,&d.{member});\n'
        else:
            mapping+=f'v.has_{name}=true;v.{name}=d.{member};\n'
            if kind=='NUMBER':mapping+=f'if(!std::isfinite(d.{member}))return false;\n'
    (out/'device_cache_encode.inc').write_text(mapping)

    (out/'protobuf_fields.inc').write_text(cpp)
    # Prost bindings and lossless adapter functions are generated together.
    rs='// Generated by scripts/generate-protobuf.py.\nuse prost::Message;\nuse super::{Value, ProtocolError};\n'
    scalar={1:('double','f64'),4:('uint64','u64'),8:('bool','bool'),9:('string','String'),12:('bytes="vec"','Vec<u8>'),13:('uint32','u32'),18:('sint64','i64')}
    def decl(f,one=False):
        typ,rt=scalar.get(f.type,('message',f.type_name.rsplit('.',1)[-1]))
        attrs=typ+(', repeated'+(', packed="false"' if f.type in (1,4,8,13,18) else '') if f.label==3 else '' if one else ', optional')+f', tag="{f.number}"'
        rt=f'Vec<{rt}>' if f.label==3 else rt if one else f'Option<{rt}>'
        return attrs,rt
    def variant(s):return ''.join(x.title() for x in s.split('_'))
    for n,m in msgs.items():
        rs+='#[derive(Clone, PartialEq, ::prost::Message)]\npub struct '+n+' {\n'
        if m.oneof_decl:
            rs+=f'#[prost(oneof="{n}Choice", tags="'+','.join(str(f.number) for f in m.field)+f'")]\npub choice: Option<{n}Choice>,\n}}\n#[derive(Clone, PartialEq, ::prost::Oneof)]\npub enum {n}Choice {{\n'
            for f in m.field:
                a,t=decl(f,True);rs+=f'#[prost({a})]\n{variant(f.name)}({t}),\n'
        else:
            for f in m.field:
                a,t=decl(f);rs+=f'#[prost({a})]\npub {"r#type" if f.name=="type" else f.name}: {t},\n'
        rs+='}\n'
    def get(f,x):
        return {1:f'Value::Float({x})',4:f'Value::Integer(i128::from({x}))',8:f'Value::Bool({x})',9:f'Value::Text({x})',12:f'Value::Bytes({x})',13:f'Value::Integer(i128::from({x}))',18:f'Value::Integer(i128::from({x}))'}.get(f.type,f'from_{f.type_name.rsplit(".",1)[-1]}({x})')
    def put(f,x):
        return {1:f'float({x})?',4:f'unsigned({x})?',8:f'boolean({x})?',9:f'text({x})?',12:f'binary({x})?',13:f'u32::try_from(unsigned({x})?).map_err(|_| ProtocolError::Malformed)?',18:f'signed({x})?'}.get(f.type,f'to_{f.type_name.rsplit(".",1)[-1]}({x})?')
    for n,m in msgs.items():
        rs+=f'fn to_{n}(v: &Value) -> Result<{n}, ProtocolError> {{\nlet mut m={n}::default();\n'
        if m.oneof_decl:
            rs+='let (key,v)=single(v)?;\nm.choice=Some(match key {\n'
            for f in m.field:rs+=f'"{f.name}" => {n}Choice::{variant(f.name)}('+put(f,'v')+'),\n'
            rs+='_ => return Err(ProtocolError::Malformed),\n});\n'
        else:
            rs+='let fields=object(v)?;\n'
            for f in m.field:
                field='r#type' if f.name=='type' else f.name
                if f.label==3:
                    rs+=f'if let Some(v)=lookup(fields,"{f.name}") {{ m.{field}=array(v)?.iter().map(|v| Ok('+put(f,'v')+')).collect::<Result<_,ProtocolError>>()?; }\n'
                else:rs+=f'if let Some(v)=lookup(fields,"{f.name}") {{ m.{field}=Some('+put(f,'v')+'); }\n'
        rs+='Ok(m)\n}\n'
        rs+=f'fn from_{n}(m: {n}) -> Value {{\nlet mut fields=Vec::new();\n'
        if m.oneof_decl:
            rs+='if let Some(v)=m.choice { let (key,v)=match v {\n'
            for f in m.field:rs+=f'{n}Choice::{variant(f.name)}(v) => ("{f.name}", '+get(f,'v')+'),\n'
            rs+='}; fields.push((Value::Text(key.into()),v)); }\n'
        else:
            for f in m.field:
                field='r#type' if f.name=='type' else f.name
                if f.label==3:
                    rs+=f'if !m.{field}.is_empty() {{ fields.push((Value::Text("{f.name}".into()),Value::Array(m.{field}.into_iter().map(|v| '+get(f,'v')+').collect()))); }\n'
                else:rs+=f'if let Some(v)=m.{field} {{ fields.push((Value::Text("{f.name}".into()), '+get(f,'v')+')); }\n'
        rs+='Value::Map(fields)\n}\n'
    rs+='pub(super) fn encode(v:&Value)->Result<Vec<u8>,ProtocolError>{Ok(to_IpcEnvelope(v)?.encode_to_vec())}\npub(super) fn decode(b:&[u8])->Result<Value,ProtocolError>{Ok(from_IpcEnvelope(IpcEnvelope::decode(b).map_err(|_|ProtocolError::Malformed)?))}\n'
    rs+='''fn object(v:&Value)->Result<&[(Value,Value)],ProtocolError>{if let Value::Map(m)=v{Ok(m)}else{Err(ProtocolError::Malformed)}}
fn lookup<'a>(m:&'a[(Value,Value)],key:&str)->Option<&'a Value>{m.iter().find(|(k,_)|matches!(k,Value::Text(s) if s==key)).map(|(_,v)|v)}
fn single(v:&Value)->Result<(&str,&Value),ProtocolError>{let m=object(v)?;if m.len()!=1{return Err(ProtocolError::Malformed)}if let Value::Text(k)=&m[0].0{Ok((k,&m[0].1))}else{Err(ProtocolError::Malformed)}}
fn array(v:&Value)->Result<&[Value],ProtocolError>{if let Value::Array(a)=v{Ok(a)}else{Err(ProtocolError::Malformed)}}
fn unsigned(v:&Value)->Result<u64,ProtocolError>{if let Value::Integer(i)=v{u64::try_from(*i).map_err(|_|ProtocolError::Malformed)}else{Err(ProtocolError::Malformed)}}
fn signed(v:&Value)->Result<i64,ProtocolError>{if let Value::Integer(i)=v{i64::try_from(*i).map_err(|_|ProtocolError::Malformed)}else{Err(ProtocolError::Malformed)}}
fn float(v:&Value)->Result<f64,ProtocolError>{match v{Value::Float(f) if f.is_finite()=>Ok(*f),Value::Integer(i)=>Ok(*i as f64),_=>Err(ProtocolError::Malformed)}}
fn boolean(v:&Value)->Result<bool,ProtocolError>{if let Value::Bool(b)=v{Ok(*b)}else{Err(ProtocolError::Malformed)}}
fn text(v:&Value)->Result<String,ProtocolError>{if let Value::Text(s)=v{Ok(s.clone())}else{Err(ProtocolError::Malformed)}}
fn binary(v:&Value)->Result<Vec<u8>,ProtocolError>{if let Value::Bytes(b)=v{Ok(b.clone())}else{Err(ProtocolError::Malformed)}}
'''
    for name,values in [('request_name',request_names),('ack_name',ack_names)]:
        rs+="pub(super) fn "+name+"(opcode: u8) -> &'static str { match opcode {\n"+''.join(str(i)+' => '+json.dumps(value)+',\n' for i,value in enumerate(values) if value)+'_ => \"\",\n} }\n'
    rs+="pub(super) struct Field { pub name: &'static str, pub tag: u32, pub kind: u32, pub message: &'static str, pub repeated: bool, pub oneof: bool }\n"
    rs+="pub(super) fn schema(name: &str) -> &'static [Field] { match name {\n"
    for name,fields in data.items():
        rs+=json.dumps(name)+' => &[\n'
        for f in fields:
            rs+='Field { name:'+json.dumps(f['name'])+', tag:'+str(f['tag'])+', kind:'+str(f['type'])+', message:'+json.dumps(f['message'])+', repeated:'+str(f['repeated']).lower()+', oneof:'+str(f['oneof']).lower()+' },\n'
        rs+='],\n'
    rs+='_ => &[],\n} }\n'
    (out/'protobuf.rs').write_text(rs.replace('Result<', 'std::result::Result<'))
    import importlib.util
    spec=importlib.util.spec_from_file_location('matter_bindings', ROOT/'scripts/generate-matter-bindings.py')
    bindings=importlib.util.module_from_spec(spec);spec.loader.exec_module(bindings);bindings.generate(out)

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        out=Path(tmp);generate(out)
        for f in out.iterdir():
            if not f.is_file():continue
            dest=ROOT/'protocol/generated'/f.name
            if args.check:
                if not dest.exists() or dest.read_bytes()!=f.read_bytes():raise SystemExit('Stale generated file: '+str(dest))
            elif not dest.exists() or dest.read_bytes()!=f.read_bytes():dest.write_bytes(f.read_bytes())
if __name__=='__main__':main()
