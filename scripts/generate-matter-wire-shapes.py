#!/usr/bin/env python3
"""Generate the native schema lookup from the shared private-wire field table."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
shapes = json.loads((root / 'protocol/matter-wire-shapes.json').read_text())
output = '// Generated by scripts/generate-matter-wire-shapes.py; do not edit.\n'
output += 'struct WireField { const char* shape; const char* name; const char* child; };\n'
output += 'const WireField wireFields[] = {\n'
for shape, fields in sorted(shapes.items()):
    for name, child in sorted(fields.items()):
        output += '    {' + ', '.join(json.dumps(s) for s in (shape, name, child)) + '},\n'
output += '};\n'
(root / 'microhad/include/matter_wire_shapes.inc').write_text(output)
rust = '// Generated by scripts/generate-matter-wire-shapes.py; do not edit.\n'
rust += 'pub(super) const FIELDS: &[(&str, &str, &str)] = &[\n'
for shape, fields in sorted(shapes.items()):
    for name, child in sorted(fields.items()):
        rust += '    (' + ', '.join(json.dumps(s) for s in (shape, name, child)) + '),\n'
rust += '];\n'
(root / 'micro-thread-matter-daemon/src/wire_shapes.rs').write_text(rust)
