package org.microhad.companion.matter

import org.junit.Assert.*
import org.junit.Test

class MatterSetupCodeTest {
    @Test fun qrLinkMatchesItsEmbeddedMatterPayload() {
        val direct = MatterSetupCode.parse(qr())
        val link = MatterSetupCode.parse("https://vendor.example/add/?r=Demo%2C${java.net.URLEncoder.encode(qr(), "UTF-8")}")
        assertEquals(direct.discriminator, link.discriminator)
        assertEquals(direct.vendorId, link.vendorId)
        assertEquals(direct.productId, link.productId)
        assertEquals(direct.bleAdvertised, link.bleAdvertised)
        assertEquals(direct.commissioningFlow, link.commissioningFlow)
        assertEquals(direct.consumePin(), link.consumePin())
    }

    @Test fun urlMatchesAnEmbeddedMatterPayloadRegardlessOfVendorOrParameter() {
        val encoded = java.net.URLEncoder.encode(qr(), "UTF-8")
        val payload = "Demo%2C$encoded"
        for (input in listOf(
            "https://vendor.example/add/?r=$payload&r=$payload",
            "https://vendor.example/commission?payload=$encoded",
            "http://vendor.example/commission?payload=$encoded",
            "https://vendor.example/commission#${qr()}")) {
            assertEquals(20202021, MatterSetupCode.parse(input).consumePin())
        }
        for (input in listOf(
            "https://vendor.example/add/?r=%ZZ",
            "https://vendor.example/add/?r=E2495",
            "https://vendor.example/commission?payload=not-a-matter-code")) {
            invalid(MatterSetupCode.Error.FORMAT) { MatterSetupCode.parse(input) }
        }
    }

    @Test fun manualCodeMatchesOnlyTheAdvertisedShortDiscriminator() {
        val code = MatterSetupCode.parse("3497-011-2332")
        assertTrue(code.shortDiscriminator)
        assertEquals(15, code.discriminator)
        assertTrue(code.matchesDiscriminator(3840))
        assertTrue(code.matchesDiscriminator(4095))
        assertFalse(code.matchesDiscriminator(3839))
        assertFalse(code.matchesDiscriminator(4096))
        assertEquals(20202021, code.consumePin())
        invalid(MatterSetupCode.Error.CONSUMED) { code.consumePin() }
        assertEquals("MatterSetupCode(redacted)", code.toString())
    }

    @Test fun manualSdkFieldVectorsAndCustomMetadata() {
        // Field vectors from connectedhomeip TestManualCode.cpp; checksum generated by table below.
        val short = MatterSetupCode.parse(withChecksum("2412950753"))
        assertEquals(10, short.discriminator)
        assertEquals(12345679, short.consumePin())
        val custom = MatterSetupCode.parse(withChecksum("64129507534536714526"))
        assertEquals(2, custom.commissioningFlow)
        assertEquals(45367, custom.vendorId)
        assertEquals(14526, custom.productId)
        assertEquals(12345679, custom.consumePin())
    }

    @Test fun manualRejectsChecksumMalformedFieldsAndForbiddenPins() {
        invalid(MatterSetupCode.Error.CHECKSUM) { MatterSetupCode.parse("34970112333") }
        for (code in listOf("", "3497011233", "3497011233x", "３4970112332", "x".repeat(513))) {
            invalid(MatterSetupCode.Error.FORMAT) { MatterSetupCode.parse(code) }
        }
        for (code in listOf("8412950753", "2666660753", "2412958192", "6412950753",
            "24129507534536714526", "64129507539999914526")) {
            invalid(MatterSetupCode.Error.FORMAT) { MatterSetupCode.parse(withChecksum(code)) }
        }
        invalid(MatterSetupCode.Error.PIN) { MatterSetupCode.parse(withChecksum("0000000000")) }
    }

    @Test fun qrHasFullDiscriminatorAndBleMetadata() {
        val code = MatterSetupCode.parse(qr())
        assertFalse(code.shortDiscriminator)
        assertEquals(3840, code.discriminator)
        assertTrue(code.matchesDiscriminator(3840))
        assertFalse(code.matchesDiscriminator(3841))
        assertEquals(65521, code.vendorId)
        assertEquals(32768, code.productId)
        assertEquals(true, code.bleAdvertised)
        assertEquals(20202021, code.consumePin())
        val onNetwork = MatterSetupCode.parse(qr(flags = 4, flow = 1))
        assertEquals(false, onNetwork.bleAdvertised)
        assertEquals(1, onNetwork.commissioningFlow)
    }

    @Test fun qrRejectsVersionPaddingFlowBase38OverflowAndPins() {
        invalid(MatterSetupCode.Error.VERSION) { MatterSetupCode.parse(qr(version = 1)) }
        invalid(MatterSetupCode.Error.FORMAT) { MatterSetupCode.parse(qr(padding = 1)) }
        invalid(MatterSetupCode.Error.FORMAT) { MatterSetupCode.parse(qr(flow = 3)) }
        for (code in listOf("MT:", "MT:A", "MT:....0....0....0....", "MT:" + "Z".repeat(19),
            "MT:" + "0".repeat(18) + "x")) {
            invalid(MatterSetupCode.Error.FORMAT) { MatterSetupCode.parse(code) }
        }
        for (pin in listOf(0, 99999999, 11111111, 22222222, 33333333, 44444444, 55555555,
            66666666, 77777777, 88888888, 12345678, 87654321)) {
            invalid(MatterSetupCode.Error.PIN) { MatterSetupCode.parse(qr(pin = pin)) }
        }
    }

    @Test fun optionalQrStructureIsBoundedAndStrictUtf8() {
        assertEquals(20202021, MatterSetupCode.parse(qr(optional = byteArrayOf(
            0x15, 0x24, 1, 3, 0x2c, 2, 2, 0xc3.toByte(), 0xa9.toByte(), 0x18))).consumePin())
        for (optional in listOf(
            byteArrayOf(0x15), byteArrayOf(0x18), byteArrayOf(0x15, 0x18, 0),
            byteArrayOf(0x15, 0x24, 1), byteArrayOf(0x15, 0x24, 1, 3, 0x24, 1, 4, 0x18),
            byteArrayOf(0x15, 0x2c, 1, 3, 0x18),
            byteArrayOf(0x15, 0x2c, 1, 1, 0xff.toByte(), 0x18),
            byteArrayOf(0x15, 0x28, 1, 0x18))) {
            invalid(MatterSetupCode.Error.FORMAT) { MatterSetupCode.parse(qr(optional = optional)) }
        }
    }

    @Test fun closeClearsAnUnconsumedSecret() {
        val code = MatterSetupCode.parse("34970112332")
        code.close()
        code.close()
        invalid(MatterSetupCode.Error.CONSUMED) { code.consumePin() }
    }

    private fun invalid(error: MatterSetupCode.Error, action: () -> Unit) {
        try { action(); fail("Expected fixed setup error") } catch (e: MatterSetupCode.Invalid) {
            assertEquals(error, e.code)
            assertEquals(error.name, e.message)
        }
    }

    // Independent tabular Verhoeff oracle; implementation uses dihedral arithmetic.
    private fun withChecksum(body: String): String {
        val d = arrayOf("0123456789", "1234067895", "2340178956", "3401289567", "4012395678",
            "5987604321", "6598710432", "7659821043", "8765932104", "9876543210")
        val p = arrayOf("0123456789", "1576283094", "5803796142", "8916043527", "9453126870",
            "4286573901", "2793806415", "7046913258")
        var c = 0
        body.reversed().forEachIndexed { i, digit -> c = d[c][p[(i + 1) % 8][digit - '0'] - '0'] - '0' }
        return body + "0432156789"[c]
    }

    private fun qr(version: Int = 0, padding: Int = 0, flow: Int = 0, flags: Int = 2,
                   pin: Int = 20202021, optional: ByteArray = byteArrayOf()): String {
        // Build the independently specified 88-bit payload, then encode three-byte little-endian groups.
        val fields = listOf(version to 3, 65521 to 16, 32768 to 16, flow to 2, flags to 8,
            3840 to 12, pin to 27, padding to 4)
        val bits = fields.flatMap { (value, width) -> (0 until width).map { (value ushr it) and 1 } }
        val bytes = ByteArray(11) { i -> (0..7).sumOf { bits[i * 8 + it] shl it }.toByte() } + optional
        val alphabet = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ-."
        return "MT:" + bytes.toList().chunked(3).joinToString("") { group ->
            var value = group.mapIndexed { i, b -> (b.toInt() and 255) shl (i * 8) }.sum()
            val width = when (group.size) { 3 -> 5; 2 -> 4; else -> 2 }
            (0 until width).map { val digit = alphabet[value % 38]; value /= 38; digit }.joinToString("")
        }
    }
}
