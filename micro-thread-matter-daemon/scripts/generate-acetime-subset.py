#!/usr/bin/env python3
"""Extract the whitelisted dependency closure from pinned AceTime generated C.

No downloads. Regeneration requires the UPSTREAM.json revision of acetimec.
Keep upstream's 2025 database anchors (needed to initialize the first year),
prune expired rules, and retain recurring rules without historical start years.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[2]
VENDOR = ROOT / 'third-party/acetimec'


def names():
    return [s for line in (ROOT / 'config/matter-time-zones.txt').read_text().splitlines()
            if (s := line.strip()) and not s.startswith('#')]


def generate(upstream, selected):
    pin = json.loads((VENDOR / 'UPSTREAM.json').read_text())
    definitions = {}
    for filename, digest in pin['database_inputs'].items():
        data = (upstream / 'src/zonedb2025' / filename).read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError('Upstream database checksum mismatch: ' + filename)
        source = re.sub(r'//[^\n]*|/\*.*?\*/', '', data.decode(), flags=re.S)
        for match in re.finditer(r'(?:static\s+)?const\s+[^;=]+?\b(kAtc\w+)\s*(?:\[\])?\s*=.*?;', source, re.S):
            definitions[match[1]] = match[0].strip()
    # Retain the upstream representation, but omit fields only used for display
    # and registration. The local bridge supplies names; offsets-only C builds
    # skip abbreviation formatting. The first year needs December 2024 rules.
    for name, text in list(definitions.items()):
        if name.startswith('kAtcZoneRules'):
            rules = []
            for rule in re.findall(r'\{([^{}]+)\}', text):
                values = [v.strip() for v in rule.split(',') if v.strip()]
                start, end = map(int, values[:2])
                if end < 2024 and start != -32767: continue
                if start != -32767: values[0] = str(max(2024, start))
                values[-1] = '0' # letters are not used in offsets-only builds
                rules.append(values)
            definitions[name] = text[:text.index('{')+1]+'\n'+',\n'.join(
                '  {'+', '.join(v)+'}' for v in rules)+'\n};'
            for policy in list(definitions):
                if policy.startswith('kAtcZonedb2025ZonePolicy') and name in definitions[policy]:
                    definitions[policy] = re.sub(r'('+re.escape(name)+r'\s*,\s*)\d+',
                                                r'\g<1>'+str(len(rules)), definitions[policy])
                    if len(rules) == 1 and rules[0][7] == '0':
                        for era in list(definitions):
                            if era.startswith('kAtcZoneEra'):
                                definitions[era] = definitions[era].replace('&'+policy, 'NULL')
    for name, text in list(definitions.items()):
        if text.startswith('const AtcZoneInfo '):
            values = [v.strip() for v in text[text.index('{')+1:text.rindex('}')].split(',') if v.strip()]
            values[0], values[1], values[-1] = '""', '0', 'NULL'
            definitions[name] = text[:text.index('{')+1]+', '.join(values)+'};'
        elif name.startswith('kAtcZoneEra'):
            definitions[name] = re.sub(r'"[^"]*"', '""', text)
    definitions['kAtcLetters'] = 'static const char * const kAtcLetters[] = {""};'
    context = definitions['kAtcZonedb2025ZoneContext']
    values = [v.strip() for v in context[context.index('{')+1:context.rindex('}')].split(',') if v.strip()]
    values[1], values[3], values[7] = '2100', '2100', '1'
    definitions['kAtcZonedb2025ZoneContext'] = context[:context.index('{')+1]+', '.join(values)+'};'
    # Resolve the graph, deduplicating identical rules, eras, and zone records.
    # Shared policies and aliases incur no duplicate processor records.
    roots = ['kAtcZonedb2025Zone'+z.replace('/', '_').replace('-', '_').replace('+', '_') for z in selected]
    ordered, canonical, bodies = [], {}, {}
    def visit(name):
        if name in canonical: return canonical[name]
        if name not in definitions: raise ValueError('Unknown generated symbol: '+name)
        text = definitions[name]
        dependencies = set(re.findall(r'\bkAtc\w+', text)) - {name}
        for dep in sorted(dependencies):
            if dep in definitions:
                replacement = visit(dep)
                text = re.sub(r'\b'+re.escape(dep)+r'\b', replacement, text)
        key = re.sub(r'\s+', '', text.replace(name, '__symbol', 1))
        if key not in bodies:
            bodies[key] = name
            ordered.append(text)
        canonical[name] = bodies[key]
        return canonical[name]
    roots = [visit(root) for root in roots]
    output = ['/* Generated by generate-acetime-subset.py; MIT, Brian T. Park. */',
              '/* TZDB '+pin['tzdb']+'; supported UTC years [2025,2100). */',
              '#include "acetimec/zone_processor.h"', '#include "zone_table.h"', *ordered]
    output.append('const struct GatewayZone gateway_zones[] = {')
    output += ['  {"'+z+'", &'+symbol+'},' for z, symbol in zip(selected, roots)]
    output += ['};', 'const unsigned gateway_zone_count = sizeof(gateway_zones)/sizeof(gateway_zones[0]);', '']
    return '\n'.join(line.rstrip() for line in '\n\n'.join(output).splitlines()).rstrip()+'\n'


def verify_sources(upstream):
    pin = json.loads((VENDOR/'UPSTREAM.json').read_text())
    for name, digest in pin['files'].items():
        if hashlib.sha256((upstream/name).read_bytes()).hexdigest() != digest:
            raise ValueError('Upstream source checksum mismatch: '+name)


def prepare_engine(destination):
    """Prepare checksum-pinned sources and apply the mailbox, offline.

    Works in Git-free source releases too. The destination must be a fresh
    build-owned directory; the dependency checkout is never modified.
    """
    upstream = VENDOR/'upstream'
    verify_sources(upstream)
    destination.mkdir(parents=True)
    pin = json.loads((VENDOR/'UPSTREAM.json').read_text())
    for name in pin['files']:
        target = destination/name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes((upstream/name).read_bytes())
    def git(*args):
        subprocess.run(['git', '-C', str(destination), '-c', 'user.name=Gateway build',
                        '-c', 'user.email=patches@localhost', '-c', 'commit.gpgsign=false',
                        '-c', 'core.hooksPath=/dev/null', *args], check=True,
                       stdout=subprocess.DEVNULL)
    git('init', '--quiet')
    git('add', '.')
    git('commit', '--quiet', '-m', 'Import pinned AceTime C engine')
    git('am', '--quiet', str(VENDOR/'offsets-only.patch'))
    for name, digest in pin['modified_files'].items():
        path = VENDOR/name if name.endswith('.patch') else destination/name
        if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            raise ValueError('Patched source checksum mismatch: '+name)
    return destination


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('upstream',type=Path,nargs='?',default=VENDOR/'upstream')
    parser.add_argument('--check',action='store_true')
    args = parser.parse_args()
    verify_sources(args.upstream)
    outputs = {VENDOR/'zones.c':generate(args.upstream,names()),
               ROOT/'micro-thread-matter-daemon/tests/fixtures/acetime-zones.c':generate(args.upstream,names()+['Australia/Lord_Howe'])}
    for path, text in outputs.items():
        if args.check:
            if path.read_text() != text: raise ValueError('Stale generated file: '+str(path))
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)

if __name__ == '__main__': main()
